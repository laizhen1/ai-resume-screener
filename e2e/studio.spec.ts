import { expect, test } from "@playwright/test";

test("role validation gates navigation and back navigation retains the résumé", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("Job description", { exact: true }).fill("Too short");
  await expect(page.getByRole("button", { name: "Continue", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Add résumé" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Review evidence" })).toBeDisabled();
  await page.getByLabel("Job description", { exact: true }).fill("We need a software engineer with Python and PostgreSQL experience building web services.");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.locator("#step-2-heading")).toBeFocused();
  const resume = "EXPERIENCE\nBuilt Python services and maintained PostgreSQL databases for an invented example company.";
  await page.getByLabel("Resume text", { exact: true }).fill(resume);
  await page.getByRole("button", { name: "Back", exact: false }).click();
  await expect(page.locator("#step-1-heading")).toBeFocused();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByLabel("Resume text", { exact: true })).toHaveValue(resume);
  await expect(page.getByRole("button", { name: "Analyse match" })).toBeEnabled();
});

test("invalid uploads cannot be analysed and valid files can be removed", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  const input = page.getByLabel("Upload resume document", { exact: true });
  for (const file of [
    { name: "sample.exe", mimeType: "application/octet-stream", buffer: Buffer.from("invalid") },
    { name: "empty.txt", mimeType: "text/plain", buffer: Buffer.from("") },
    { name: "oversized.txt", mimeType: "text/plain", buffer: Buffer.alloc(5 * 1024 * 1024 + 1) }
  ]) {
    await input.setInputFiles(file);
    await expect(page.locator("main").getByRole("alert")).toContainText("up to 5 MB");
    await expect(page.getByRole("button", { name: "Analyse match" })).toBeDisabled();
  }
  await input.setInputFiles({ name: "fictional-profile.txt", mimeType: "text/plain", buffer: Buffer.from("Fictional Python engineer résumé") });
  await expect(page.getByText("fictional-profile.txt", { exact: true }).first()).toBeVisible();
  await expect(page.locator("main").getByRole("alert")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Analyse match" })).toBeEnabled();
  await page.getByRole("button", { name: "Remove file", exact: true }).click();
  await expect(page.getByLabel("Resume text", { exact: true })).toBeVisible();
  expect(await input.evaluate((element: HTMLInputElement) => element.files?.length)).toBe(0);
  await expect(page.getByRole("button", { name: "Analyse match" })).toBeDisabled();
});

test("fictional generation replaces an upload and keeps navigation locked while pending", async ({ page }) => {
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  const resume = "FICTIONAL PROFILE\nBuilt Python services and maintained databases for an invented example company.";
  await page.route("**/api/generate", async route => { await pending; await route.fulfill({ json: { text: resume, source: "offline" } }); });
  await page.goto("/");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Upload resume document").setInputFiles({ name: "example.txt", mimeType: "text/plain", buffer: Buffer.from("Fictional uploaded document") });
  await page.getByText("Create another fictional profile", { exact: true }).click();
  await page.getByRole("button", { name: "Generate fictional resume" }).click();
  await expect(page.getByRole("button", { name: "Define role" })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Load guided example" })).toBeDisabled();
  release();
  await expect(page.getByLabel("Resume text", { exact: true })).toHaveValue(resume);
  expect(await page.getByLabel("Upload resume document").evaluate((element: HTMLInputElement) => element.files?.length)).toBe(0);
  await expect(page.getByRole("status").filter({hasText:"Generated by"})).toContainText("built-in offline generator");
  await expect(page.getByRole("button", { name: "Analyse match" })).toBeEnabled();
});

test("shared navigation, brand and responsive pages work at narrow widths", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 });
  await page.goto("/");
  await expect(page.getByRole("link", { name: "Open Resume Lab home" })).toBeVisible();
  await page.keyboard.press("Tab");
  await expect(page.getByRole("link", { name: "Skip to content" })).toBeFocused();
  for (const [link, route] of [["Workspace", "/workspace"], ["Evaluation", "/evaluation"], ["Regression suite", "/evaluation/regression"], ["Sign in", "/login"], ["New analysis", "/"]]) {
    await page.getByRole("link", { name: link, exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`${route === "/" ? "/" : route}$`));
    await expect(page.locator("main#main-content")).toHaveCount(1);
    await expect(page.getByRole("navigation", { name: "Main navigation", exact: true })).toHaveCount(1);
    await expect(page.locator("h1")).toBeVisible();
    const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
    expect(dimensions.content, `${route}: ${JSON.stringify(dimensions)}`).toBeLessThanOrEqual(dimensions.viewport);
  }
  await expect(page.getByRole("link", { name: "New analysis", exact: true })).toHaveAttribute("aria-current", "page");
  await page.screenshot({ path: "test-results/studio-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.screenshot({ path: "test-results/studio-desktop.png", fullPage: true });
});

test("progress steps fit a narrow screen with wider fallback font metrics", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 800 });
  await page.goto("/");
  await page.getByRole("button", { name: "Load guided example" }).waitFor();
  await page.addStyleTag({ content: "body { font-family: monospace; }" });
  const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
  expect(dimensions.content, JSON.stringify(dimensions)).toBeLessThanOrEqual(dimensions.viewport);
  await page.getByRole("button", { name: "Load guided example" }).click();
  await expect(page.getByRole("button", { name: "Analyse match", exact: true })).toBeEnabled();
});
